/// <reference types="vitest/config" />
import { defineConfig, loadEnv, type Plugin } from 'vite'
import react from '@vitejs/plugin-react'
import { VitePWA } from 'vite-plugin-pwa'
import { isSecretSupabaseKey } from './src/lib/supabaseKey.ts'

// Paper colour from src/styles/tokens.css: the installed app's background and theme colour.
// (index.html carries the dark-theme theme-color; the manifest has no dark variant.)
const PAPER = '#f6f3ee'

/**
 * Fails the build if a secret key is about to be published. The running app refuses one as well
 * (src/lib/env.ts), but by then it is already in JavaScript anyone can download.
 */
function refuseSecretKey(): Plugin {
  return {
    name: 'redpen:refuse-secret-key',
    apply: 'build',
    config(_config, { mode }) {
      const env = loadEnv(mode, process.cwd(), 'VITE_')
      for (const name of ['VITE_SUPABASE_PUBLISHABLE_KEY', 'VITE_SUPABASE_ANON_KEY']) {
        if (isSecretSupabaseKey(env[name] ?? '')) {
          throw new Error(
            `${name} holds your Supabase secret key, and this build would publish it for anyone to read. ` +
              'Use the publishable key (sb_publishable_...) instead, and treat the secret key as compromised: rotate it in Supabase.',
          )
        }
      }
    },
  }
}

